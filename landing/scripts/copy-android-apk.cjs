const fs = require('fs')
const path = require('path')

const candidates = [
  path.join(__dirname, '..', 'android', 'app', 'build', 'outputs', 'apk', 'release', 'app-release.apk'),
  path.join(__dirname, '..', 'android', 'app', 'build', 'outputs', 'apk', 'release', 'app-release-unsigned.apk'),
  path.join(__dirname, '..', 'android', 'app', 'build', 'outputs', 'apk', 'debug', 'app-debug.apk'),
]

const src = candidates.find((p) => fs.existsSync(p))
if (!src) {
  console.error('[copy-android-apk] No APK found. Run npm run build:android-apk first.')
  process.exit(1)
}

function readGradleVersion() {
  const gradlePath = path.join(__dirname, '..', 'android', 'app', 'build.gradle')
  const text = fs.readFileSync(gradlePath, 'utf8')
  const versionName = text.match(/versionName\s+"([^"]+)"/)?.[1] || null
  const versionCode = Number(text.match(/versionCode\s+(\d+)/)?.[1] || 0)
  return { versionName, versionCode }
}

const outDir = path.join(__dirname, '..', 'release-android')
fs.mkdirSync(outDir, { recursive: true })
const dest = path.join(outDir, 'VeilAssist-Interview.apk')
fs.copyFileSync(src, dest)
const size = fs.statSync(dest).size
console.log(`[copy-android-apk] ${dest} (${size} bytes)`)

const publicDir = path.join(__dirname, '..', 'public', 'downloads')
fs.mkdirSync(publicDir, { recursive: true })
const publicDest = path.join(publicDir, 'VeilAssist-Interview.apk')
fs.copyFileSync(src, publicDest)
console.log(`[copy-android-apk] ${publicDest} (${size} bytes)`)

const { versionName, versionCode } = readGradleVersion()
const manifest = {
  fileName: 'VeilAssist-Interview.apk',
  version: versionName,
  versionCode,
  size,
  builtAt: new Date().toISOString(),
}
const manifestPath = path.join(publicDir, 'apk-manifest.json')
fs.writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8')
console.log(`[copy-android-apk] ${manifestPath} → ${versionName} (${versionCode})`)

const generatedTs = path.join(__dirname, '..', 'src', 'config', 'apkManifest.generated.ts')
fs.writeFileSync(
  generatedTs,
  `/** Auto-generated by scripts/copy-android-apk.cjs — do not edit. */\nexport const SITE_ANDROID_APK_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const\n`,
  'utf8',
)
console.log(`[copy-android-apk] ${generatedTs}`)
